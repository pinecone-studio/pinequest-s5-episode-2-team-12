// Builds the static map of «Монголын аялал»: aimag borders + country outline as SVG paths, and the 26
// stops projected with the same projection. Output: src/features/roadmap/map/mongolia.generated.ts
// Run: bun run roadmap:map   (only needed when the source data, the projection or a stop's lat/lng changes)
//
// Source: Natural Earth 1:10m admin-1 states/provinces (public domain), filtered to Mongolia
// (21 aimags + Ulaanbaatar) into scripts/roadmap/data/mng-admin1.geojson.
import { geoArea, geoConicConformal, geoPath } from 'd3-geo';
import type { FeatureCollection, MultiPolygon, Polygon } from 'geojson';
// @ts-expect-error mapshaper ships no types
import mapshaper from 'mapshaper';
import { STOPS } from '../../src/features/roadmap/stops';

export const MAP_WIDTH = 1000;
const PAD = 24;
/** Share of vertices mapshaper keeps; tuned so the output stays ~25 KB while small aimags keep their shape. */
const KEEP = '20%';

type Geo = FeatureCollection<Polygon | MultiPolygon, { iso: string; name: string }>;

const here = new URL('.', import.meta.url).pathname;
const SRC = `${here}data/mng-admin1.geojson`;
const OUT = `${here}../../src/features/roadmap/map/mongolia.generated.ts`;

async function simplify(input: Geo, extra = ''): Promise<Geo> {
  const out = await mapshaper.applyCommands(
    `-i in.json -simplify ${KEEP} keep-shapes ${extra} -o out.json format=geojson`,
    { 'in.json': input },
  );
  return JSON.parse(String(out['out.json']));
}

/** The projection used for both the borders and the stop points. */
export function makeProjection(geo: Geo) {
  return geoConicConformal()
    .parallels([44, 50])
    .rotate([-103, 0])
    .fitWidth(MAP_WIDTH - PAD * 2, geo);
}

const r1 = (n: number) => Math.round(n * 10) / 10;

/** d3-geo wants clockwise outer rings; a ring wound the other way means "the whole globe minus the aimag". */
function rewind<G extends Polygon | MultiPolygon>(g: G): G {
  if (geoArea(g) <= 2 * Math.PI) return g;
  const flip = (rings: number[][][]) => rings.map((r) => [...r].reverse());
  return (
    g.type === 'Polygon'
      ? { ...g, coordinates: flip(g.coordinates) }
      : { ...g, coordinates: g.coordinates.map(flip) }
  ) as G;
}

async function main() {
  const source = (await Bun.file(SRC).json()) as Geo;
  const aimags = await simplify(source);
  // dissolve drops properties, so mapshaper returns a bare GeometryCollection
  const outline = (await simplify(source, '-dissolve')) as unknown as { geometries: Polygon[] };

  const projection = makeProjection(source);
  const [[x0, y0], [, y1]] = geoPath(projection).bounds(source);
  projection.translate([projection.translate()[0] - x0 + PAD, projection.translate()[1] - y0 + PAD]);
  const height = Math.ceil(y1 - y0 + PAD * 2);
  const path = geoPath(projection).digits(1);

  const regions = aimags.features
    .map((f) => ({ iso: f.properties.iso, name: f.properties.name, d: path(rewind(f.geometry)) ?? '' }))
    .sort((a, b) => a.iso.localeCompare(b.iso));
  const country = path(rewind(outline.geometries[0])) ?? '';
  const points = Object.fromEntries(
    STOPS.map((s) => {
      const p = projection([s.lng, s.lat]);
      if (!p) throw new Error(`stop ${s.no} is outside the projection`);
      return [s.no, [r1(p[0]), r1(p[1])]];
    }),
  );

  const body = `// GENERATED by scripts/roadmap/build-map.ts — do not edit. Run \`bun run roadmap:map\`.
// Natural Earth 1:10m admin-1 (public domain), conic conformal projection, ${KEEP} of vertices kept.

export const MAP = {
  width: ${MAP_WIDTH},
  height: ${height},
  outline: ${JSON.stringify(country)},
  aimags: ${JSON.stringify(regions, null, 2)},
  /** Stop number → projected [x, y] in map units. */
  points: ${JSON.stringify(points)} as Record<number, [number, number]>,
} as const;
`;
  await Bun.write(OUT, body);
  console.log(
    `✓ ${OUT.split('/src/')[1]}: ${regions.length} aimags, ${STOPS.length} stops, ${(body.length / 1024).toFixed(1)} KB`,
  );
}

if (import.meta.main) await main();
