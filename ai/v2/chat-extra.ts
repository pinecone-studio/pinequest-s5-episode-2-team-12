/** Cyrillic → the Latin letters students type on phones ("Зөвлөгөө өгөөч" → "zuvlugu oguuch"). */
export function toLatin(text: string): string {
  return [...text.toLowerCase()].map((c) => LATIN[c] ?? c).join('');
}

/** Chat request phrases the app and training data use (end of the user message). */
const ASK_END = /\n\n([^\n$]+)$/;

/** Same conversation, but the student's request line is typed in Latin letters. */
export function latinVariant(row: Row): Row | null {
  const user = row.messages[1];
  if (!user || user.role !== 'user') return null;
  const m = ASK_END.exec(user.content);
  if (!m?.[1] || !/[Ѐ-ӿ]/.test(m[1])) return null;
  const content = user.content.replace(ASK_END, `\n\n${toLatin(m[1])}`);
  return {
    ...row,
    id: `${row.id}-lat`,
    messages: [row.messages[0] as Message, { role: 'user', content }, ...row.messages.slice(2)],
  };
}

